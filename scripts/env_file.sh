#!/usr/bin/env bash
# .env에서 값 하나를 꺼내 온다 — install.sh·check.sh·db_dump.sh·db_restore.sh가 source로 함께 읽는다.
# source: 외부 파일에 작성된 셸 스크립트를 현재 실행 중인 셸 환경으로 직접 읽어와 실행하는 명령어
# 
# [배경]
# .env는 Compose가 읽는 데이터 파일이지 셸 스크립트가 아니다.
# 그런데 셸에서 값을 꺼내려고 `source .env`를 쓰면 파일의 내용이 명령으로 실행된다.
# 그래서 값에 특별한 글자가 들어가면, 값을 읽으려던 스크립트가 엉뚱한 이유로 죽는다.
#
#   POSTGRES_PASSWORD=Str0ng$Pass   → `$Pass`를 변수로 보고 "unbound variable"로 즉사한다
#   POSTGRES_PASSWORD=my secret pw  → `secret`을 명령으로 보고 "command not found"로 즉사한다
#   POSTGRES_PASSWORD=a`id -un`b    → 백틱 안의 명령이 실제로 실행되어 값이 뒤바뀐다
#
# Compose는 세 경우 모두 글자 그대로 읽는다.
# 그래서 스택은 멀쩡한데 스크립트만 죽고, 사용자에게 남는 단서는 오류 한 줄뿐인 상황이 생긴다.
# 비밀번호에 `$`를 넣는 것은 아주 흔한 일이므로 실제로 일어날 수 있는 일이다.
#
# [목적]
# 파일을 실행하지 않고 필요한 줄에서 글자만 꺼내 온다.
#
# [쓰는 법]
#   source "$ROOT/scripts/env_file.sh"
#   APP_HOST_PORT="${APP_HOST_PORT:-$(read_env APP_HOST_PORT)}"
#   이후에는 "${APP_HOST_PORT:-8000}"처럼 기본값과 함께 쓴다.
#
# 셸 환경변수를 앞에 두는 이유는 Docker Compose와 우선순위를 맞추기 위해서다.
# 그래야 `APP_HOST_PORT=3000 ./check.sh`처럼 한 번만 다른 값을 주는 방식이 그대로 통한다.

# .env에서 키 하나의 값을 표준 출력으로 내보낸다. 파일이나 키가 없으면 아무것도 내보내지 않는다.
# 같은 키가 여러 번 적혀 있으면 마지막 줄을 쓴다. 셸이 파일을 읽을 때와 같은 규칙이다.
# 주석 줄은 키 앞에 `#`이 붙어 있어서 애초에 걸리지 않는다.
# 값 뒤의 공백과 값을 감싼 따옴표는 벗긴다. Compose도 같은 값으로 읽으므로 그쪽과 어긋나지 않는다.

# [문법]
  # sed -n ... p: 해당하는 줄만 찾아서 출력
  # s / ^[[:space:]]*$1= /  / p
  # ┬   ────────┬───────   ┬  ┬
  # │           │          │  └─ 치환 성공한 줄만 화면에 출력(p)해라
  # │           │          └──── 아무것도 안 넣었으니 그냥 지워라
  # │           └─────────────── 이 모양(공백+변수명+=)을 찾아서
  # └─────────────────────────── 치환(s)을 시작한다
  # tail -n 1: 마지막 줄만 출력
  # DB_PORT=5432
  # ... 중간에 다른 설정들 ...
  # DB_PORT=5433
  # tail -n 1을 써서 DB_PORT가 중복 정의되었을 때 5433만 선택된다.
  # sed는 명령 1개만 실행하지만, -e '명령1' -e '명령2' -e '명령3' 형태로 적으면 데이터 1줄에 대해 3가지 작업을 순서대로 연달아 수행

  # ^"\(.*\)"$ : 전체가 큰따옴표로 감싸인 경우, 안의 내용만 남김
  # ^'\(.*\)'$ : 전체가 작은따옴표로 감싸인 경우, 안의 내용만 남김

  # [[:space:]]*$ : 줄 끝($)에 붙어 있는 공백이나 탭([[:space:]]*)
  # 괄호 앞에 역슬래시를 붙여 \( ... \) 형태로 감싸면, 그 안쪽에 매칭된 내용을 메모리에 순서대로 임시 저장
  
read_env() {
  [ -f .env ] || return 0
  sed -n "s/^[[:space:]]*$1=//p" .env \
    | tail -n 1 \
    | sed -e 's/[[:space:]]*$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'\$/\1/"
}
